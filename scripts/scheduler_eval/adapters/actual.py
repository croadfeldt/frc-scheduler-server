"""Adapter for "actual played schedules" — schedules pulled from
records of past events rather than generated by an algorithm.

Two sources:
  - CSV files in the reviewer's format (Type, Match, Day, Time, Blue 1-3, Red 1-3, Surrogates)
  - TBA API for past FRC events (uses the existing app.tba client for
    auth + rate-limit handling)

This adapter doesn't generate; it loads. Useful as a baseline — "what
did FRC actually publish for this event" is the implicit reference for
"good enough."

For TBA, you need the TBA_API_KEY env var set. Without it, the existing
app.tba module raises a clear RuntimeError. Free public read access
exists for these endpoints; the key just provides rate-limit headroom.
"""

from __future__ import annotations

import asyncio
import csv
import time
from datetime import datetime, timezone
from pathlib import Path
import re

from .base import Adapter
from ..harness_types import Fixture, Match, Schedule


# Match the existing import path's logic for translating TBA team_keys
# into team numbers ("frc2530" -> 2530). Lifted out of app/main.py so
# the harness doesn't need to import the running app.
_TEAM_KEY_RE = re.compile(r"^frc(\d+)$")


def _team_key_to_num(team_key: str) -> int:
    """Translate a TBA team key like 'frc2530' to the integer team number."""
    m = _TEAM_KEY_RE.match(team_key.strip())
    if not m:
        raise ValueError(f"Unrecognized TBA team key: {team_key!r}")
    return int(m.group(1))


def _surrogate_flags(teams: list[int], surrogate_keys: list[str] | None) -> list[bool]:
    """Build a positional surrogate flag list from TBA's surrogate_team_keys.

    TBA reports surrogates as a list of team_keys (not positional indices),
    so we have to look up which positions they occupy. If surrogate_keys
    is None or empty, all flags are False.
    """
    if not surrogate_keys:
        return [False] * len(teams)
    surrogate_nums = {_team_key_to_num(k) for k in surrogate_keys}
    return [t in surrogate_nums for t in teams]


def _qual_match_number(match_key: str) -> int:
    """Extract qual match number from a TBA match key like '2024mnst_qm12'."""
    m = re.search(r"_qm(\d+)$", match_key)
    if not m:
        raise ValueError(f"Match key is not a qual match: {match_key!r}")
    return int(m.group(1))


class ActualScheduleAdapter(Adapter):
    """Loads a previously-published schedule rather than generating one."""

    name = "actual"

    def __init__(self, csv_path: Path | str | None = None,
                 tba_event_key: str | None = None,
                 tba_api_key: str | None = None):
        """Either csv_path OR tba_event_key must be provided.

        For TBA, the harness uses the app.tba client which reads
        TBA_API_KEY from the environment. The tba_api_key parameter
        here is for future use if we want to override at the call site;
        for now it's accepted but the env var is what gets used.
        """
        if csv_path is None and tba_event_key is None:
            raise ValueError("ActualScheduleAdapter requires csv_path or tba_event_key")
        self.csv_path = Path(csv_path) if csv_path else None
        self.tba_event_key = tba_event_key
        self.tba_api_key   = tba_api_key

    def generate(self, fixture: Fixture, *, seed: int | None = None,
                 trial: int = 0) -> Schedule:
        """Returns the published schedule. Ignores seed and trial —
        the actual schedule is what it is, no resampling.
        """
        t0 = time.monotonic()
        if self.csv_path:
            matches = self._parse_csv(self.csv_path)
            source = "csv"
        else:
            matches = self._fetch_from_tba()
            source = "tba"
        elapsed = time.monotonic() - t0

        return Schedule(
            fixture_id=fixture.fixture_id,
            adapter_name=self.name,
            matches=matches,
            generation_seconds=elapsed,
            seed=None,
            adapter_diagnostics={
                "source":         source,
                "path":           str(self.csv_path) if self.csv_path else None,
                "tba_event_key":  self.tba_event_key,
            },
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

    @staticmethod
    def _parse_csv(path: Path) -> list[Match]:
        matches = []
        with open(path) as f:
            for row in csv.DictReader(f):
                if row["Type"] != "Qualification":
                    continue
                mn = int(row["Match"].lstrip("Q"))
                blue = [int(row[f"Blue {i}"]) for i in (1, 2, 3)]
                red  = [int(row[f"Red {i}"])  for i in (1, 2, 3)]
                surr_str = (row.get("Surrogates") or "").strip()
                surr_teams: set[int] = set()
                if surr_str:
                    surr_teams = {int(s.strip()) for s in surr_str.split(",") if s.strip()}
                matches.append(Match(
                    match_num=mn, blue=blue, red=red,
                    blue_surrogate=[t in surr_teams for t in blue],
                    red_surrogate=[t in surr_teams for t in red],
                ))
        matches.sort(key=lambda m: m.match_num)
        return matches

    def _fetch_from_tba(self) -> list[Match]:
        """Fetch the played qualification schedule from The Blue Alliance."""
        if not self.tba_event_key:
            raise ValueError("tba_event_key is required for TBA fetch")
        # Use the existing app.tba client. asyncio.run is fine here —
        # this is called from a sync adapter generate() that runs in
        # a process pool worker, so no event loop conflict.
        try:
            from app import tba as tba_client
        except ImportError as e:
            raise RuntimeError(
                "Cannot import app.tba — run the harness from the repo root "
                "or add the repo to PYTHONPATH"
            ) from e
        tba_matches = asyncio.run(tba_client.get_event_matches(self.tba_event_key))
        return self._parse_tba_matches(tba_matches)

    @staticmethod
    def _parse_tba_matches(tba_matches: list[dict]) -> list[Match]:
        """Convert TBA's match shape into our Match list.

        TBA returns all matches (qual + playoff). We filter to comp_level=='qm'
        because the harness only evaluates qualification scheduling. Playoffs
        use a different model (alliance picks) that's outside scope.
        """
        quals = [m for m in tba_matches if m.get("comp_level") == "qm"]
        out: list[Match] = []
        for m in quals:
            alliances = m.get("alliances") or {}
            red  = alliances.get("red")  or {}
            blue = alliances.get("blue") or {}
            red_teams  = [_team_key_to_num(k) for k in (red.get("team_keys")  or [])]
            blue_teams = [_team_key_to_num(k) for k in (blue.get("team_keys") or [])]
            red_surr   = _surrogate_flags(red_teams,  red.get("surrogate_team_keys"))
            blue_surr  = _surrogate_flags(blue_teams, blue.get("surrogate_team_keys"))
            out.append(Match(
                match_num=_qual_match_number(m["key"]),
                blue=blue_teams, red=red_teams,
                blue_surrogate=blue_surr, red_surrogate=red_surr,
            ))
        out.sort(key=lambda mm: mm.match_num)
        return out
